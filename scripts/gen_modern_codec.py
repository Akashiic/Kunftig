#!/usr/bin/env python3
"""
Generates the arity-heavy parts of com.akashic.kunftig.modern (FunctionN, record codec products/groups and
StreamCodec.composite overloads). Run from the repository root after editing:  python3 scripts/gen_modern_codec.py
"""
import os

BASE = 'src/main/java/com/akashic/kunftig/modern'
PKG = 'com.akashic.kunftig.modern'
MAX_COMPOSITE = 17
MAX_GROUP = 16
HEADER = '// Generated by scripts/gen_modern_codec.py: do not edit by hand.\n'


def write(rel, text):
    path = os.path.join(BASE, rel)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, 'w') as f:
        f.write(text)


def fn_type(n):
    if n == 1:
        return 'java.util.function.Function'
    if n == 2:
        return 'java.util.function.BiFunction'
    return f'{PKG}.function.Function{n}'


for n in range(3, MAX_COMPOSITE + 1):
    ts = ', '.join(f'T{i}' for i in range(1, n + 1))
    ps = ', '.join(f'T{i} t{i}' for i in range(1, n + 1))
    write(f'function/Function{n}.java', f'''{HEADER}package {PKG}.function;

/** A function of {n} arguments. */
@FunctionalInterface
public interface Function{n}<{ts}, R> {{

    R apply({ps});
}}
''')

products = []
groups = []
for n in range(1, MAX_GROUP + 1):
    ts = ', '.join(f'T{i}' for i in range(1, n + 1))
    fields = '\n'.join(f'        private final RecordCodecBuilder<O, T{i}> f{i};' for i in range(1, n + 1))
    params = ', '.join(f'RecordCodecBuilder<O, T{i}> f{i}' for i in range(1, n + 1))
    assign = '\n'.join(f'            this.f{i} = f{i};' for i in range(1, n + 1))
    encode = '\n'.join(f'                f{i}.encodeField(value, tag);' for i in range(1, n + 1))
    decode = ', '.join(f'f{i}.decodeField(tag)' for i in range(1, n + 1))
    args = ', '.join(f'f{i}' for i in range(1, n + 1))
    products.append(f'''
    /** Fields of a record with {n} component(s). */
    public static final class P{n}<O, {ts}> {{

{fields}

        P{n}({params}) {{
{assign}
        }}

        public RecordCodecBuilder<O, O> apply(RecordCodecBuilder.Instance<O> instance, {fn_type(n)}<{ts}, O> factory) {{
            return RecordCodecBuilder.root((value, tag) -> {{
{encode}
            }}, tag -> factory.apply({decode}));
        }}
    }}
''')
    groups.append(f'''
    public <{ts}> Products.P{n}<O, {ts}> group({params}) {{
        return new Products.P{n}<>({args});
    }}
''')

write('codec/Products.java', f'''{HEADER}package {PKG}.codec;

/** Field groups of {{@link RecordCodecBuilder.Instance#group}}, as DFU's {{@code Products}}. */
public final class Products {{

    private Products() {{}}
{''.join(products)}}}
''')
write('codec/RecordCodecBuilderGroups.java', f'''{HEADER}package {PKG}.codec;

/** The {{@code group(...)}} overloads of {{@link RecordCodecBuilder.Instance}}. */
abstract class RecordCodecBuilderGroups<O> {{
{''.join(groups)}}}
''')

composites = []
for n in range(1, MAX_COMPOSITE + 1):
    ts = ', '.join(f'T{i}' for i in range(1, n + 1))
    params = ',\n        '.join(
        f'StreamCodec<? super B, T{i}> codec{i}, java.util.function.Function<C, T{i}> getter{i}' for i in range(1, n + 1))
    decode = '\n'.join(f'                T{i} t{i} = codec{i}.decode(buf);' for i in range(1, n + 1))
    encode = '\n'.join(f'                codec{i}.encode(buf, getter{i}.apply(value));' for i in range(1, n + 1))
    args = ', '.join(f't{i}' for i in range(1, n + 1))
    composites.append(f'''
    public static <B, C, {ts}> StreamCodec<B, C> composite(
        {params},
        {fn_type(n)}<{ts}, C> factory) {{
        return new StreamCodec<B, C>() {{

            @Override
            public C decode(B buf) {{
{decode}
                return factory.apply({args});
            }}

            @Override
            public void encode(B buf, C value) {{
{encode}
            }}
        }};
    }}
''')

write('codec/StreamCodec.java', f'''{HEADER}package {PKG}.codec;

import java.util.function.BiConsumer;
import java.util.function.Function;

/**
 * Network codec over a buffer type {{@code B}} (normally {{@code io.netty.buffer.ByteBuf}}), with the modern
 * {{@code StreamCodec}} API: {{@code of}}, {{@code map}}, {{@code dispatch}} and {{@code composite}} for records of
 * 1 to {MAX_COMPOSITE} fields.
 */
public interface StreamCodec<B, V> extends StreamDecoder<B, V>, StreamEncoder<B, V> {{

    static <B, V> StreamCodec<B, V> of(StreamEncoder<B, V> encoder, StreamDecoder<B, V> decoder) {{
        return new StreamCodec<B, V>() {{

            @Override
            public V decode(B buf) {{
                return decoder.decode(buf);
            }}

            @Override
            public void encode(B buf, V value) {{
                encoder.encode(buf, value);
            }}
        }};
    }}

    static <B, V> StreamCodec<B, V> ofMember(BiConsumer<V, B> encoder, StreamDecoder<B, V> decoder) {{
        return of((buf, value) -> encoder.accept(value, buf), decoder);
    }}

    static <B, V> StreamCodec<B, V> unit(V value) {{
        return of((buf, ignored) -> {{}}, buf -> value);
    }}

    default <O> StreamCodec<B, O> map(Function<? super V, ? extends O> to, Function<? super O, ? extends V> from) {{
        StreamCodec<B, V> self = this;
        return of((buf, value) -> self.encode(buf, from.apply(value)), buf -> to.apply(self.decode(buf)));
    }}

    default <O> StreamCodec<B, O> dispatch(Function<? super O, ? extends V> keyGetter,
        Function<? super V, ? extends StreamCodec<? super B, ? extends O>> codecGetter) {{
        StreamCodec<B, V> self = this;
        return new StreamCodec<B, O>() {{

            @Override
            public O decode(B buf) {{
                return codecGetter.apply(self.decode(buf))
                    .decode(buf);
            }}

            @Override
            @SuppressWarnings("unchecked")
            public void encode(B buf, O value) {{
                V key = keyGetter.apply(value);
                self.encode(buf, key);
                ((StreamCodec<B, O>) codecGetter.apply(key)).encode(buf, value);
            }}
        }};
    }}
{''.join(composites)}}}
''')
print('generated')
